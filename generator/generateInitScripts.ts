import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import type { Language } from "./languages";

/**
 * Build the generated `init.d.ts` source.
 *
 * @param languages The supported languages.
 * @returns The TypeScript definition source.
 */
export const createInitTypescriptDefs = (languages: Language[]) =>
    `// Generated by \`pnpm generate\`. Do not edit by hand.
import type { Operands } from "../numbers/operands";
import type { PluralizationCount } from "../numbers/pluralization";

/**
 * The supported languages for localization.
 */
export const LanguageCodes: Readonly<
    [
${languages.map((language) => `        "${language.code}",`).join("\n")}
    ]
>;

/**
 * A supported language for localization.
 */
export type LanguageCode = (typeof LanguageCodes)[number];

/**
 * Convert a Roblox \`LocaleId\` to a supported \`LanguageCode\`.
 *
 * @param localeId The Roblox \`LocaleId\` to convert.
 * @returns The corresponding \`LanguageCode\`, or \`undefined\` if the \`LocaleId\`
 *          is not supported.
 */
export const robloxLocaleIdToLanguageCode: (
    localeId: string,
) => LanguageCode | undefined;

/**
 * Metadata for a supported language.
 */
export interface Metadata {
    /**
     * The name of the language, in English.
     */
    name: string;
    /**
     * The name of the language, in the language itself.
     */
    nativeName: string;
    /**
     * The CLDR code for the language.
     */
    cldrCode: string;
    /**
     * The Roblox \`LocaleId\` for the language.
     */
    robloxLocaleId: string;
}

/**
 * A mapping of supported languages to their metadata.
 */
export const LanguageMetadata: Readonly<{
    [code in LanguageCode]: Metadata;
}>;

/**
 * Pluralization functions for a supported language.
 */
export interface PluralizationFunctions {
    /**
     * The pluralization function for cardinal numbers.
     *
     * @param operands The CLDR operands for the number.
     * @returns The plural category for the number.
     */
    cardinal: (operands: Operands) => PluralizationCount;
    /**
     * The counts the language uses for cardinal numbers.
     */
    cardinalCounts: readonly PluralizationCount[];
    /**
     * The pluralization function for ordinal numbers.
     *
     * @param operands The CLDR operands for the number.
     * @returns The plural category for the number.
     */
    ordinal: (operands: Operands) => PluralizationCount;
    /**
     * The counts the language uses for ordinal numbers.
     */
    ordinalCounts: readonly PluralizationCount[];
}

/**
 * Data on how numbers should be formatted.
 */
export interface NumberFormattingData {
    /**
     * The number symbols for the locale.
     */
    symbols: {
        decimal: string;
        group: string;
        minusSign: string;
        plusSign: string;
        percentSign: string;
        infinity: string;
        nan: string;
    };
    /**
     * The primary and secondary grouping sizes.
     */
    grouping: {
        primary: number;
        secondary: number;
    };
    /**
     * Compact decimal patterns, by magnitude then plural count.
     */
    compact: {
        short: {
            [magnitude: string]: Partial<Record<PluralizationCount, string>>;
        };
        long: {
            [magnitude: string]: Partial<Record<PluralizationCount, string>>;
        };
    };
}

/**
 * The pluralization rules and number formatting data for a supported language.
 */
export interface LanguageConfiguration {
    pluralization: PluralizationFunctions;
    numberFormatting: NumberFormattingData;
}

/**
 * Get the configuration for a supported language.
 *
 * @param languageCode The language code to get the configuration for.
 * @returns The configuration for the specified language.
 */
export const getLanguageConfiguration: (
    languageCode: LanguageCode,
) => LanguageConfiguration;
`;

/**
 * Build the generated `init.luau` index module.
 *
 * @param languages The supported languages.
 * @returns The Luau module source.
 */
const createInitLuau = (languages: Language[]): string => {
    const codeUnion = languages
        .map((language) => `    | "${language.code}"`)
        .join("\n");
    const codeList = languages
        .map((language) => `    "${language.code}",`)
        .join("\n");
    const robloxEntries = languages
        .map(
            (language) =>
                `    ["${language.robloxLocaleId}"] = "${language.code}",`,
        )
        .join("\n");
    const languageMetadataEntries = languages
        .map(
            (language) =>
                `    ["${language.code}"] = {
        name = "${language.name}",
        nativeName = "${language.nativeName}",
        cldrCode = "${language.cldrCode}",
        robloxLocaleId = "${language.robloxLocaleId}",
    },`,
        )
        .join("\n");

    return `--!strict
-- Generated by generator/main.ts. Do not edit by hand.

local operandsModule = require("./numbers/operands")
local pluralizationModule = require("./numbers/pluralization")

type Operands = operandsModule.Operands
type PluralizationCount = pluralizationModule.PluralizationCount

local module = {}

--[=[
    A supported language for localization.
]=]
export type LanguageCode =
${codeUnion}

--[=[
    The supported languages for localization.
]=]
module.LanguageCodes = {
${codeList}
} :: { LanguageCode }

--[=[
    Internal mapping of Roblox \`LocaleId\`s to supported \`LanguageCode\`s.
]=]
local robloxLocaleIds: { [string]: LanguageCode } = {
${robloxEntries}
}

--[=[
    Convert a Roblox \`LocaleId\` to a supported \`LanguageCode\`.

    @param localeId The Roblox \`LocaleId\` to convert.
    @return The corresponding \`LanguageCode\`, or \`nil\` if unsupported.
]=]
function module.robloxLocaleIdToLanguageCode(
    localeId: string
): LanguageCode?
    return robloxLocaleIds[localeId:lower()]
end

--[=[
    Metadata for a supported language.
]=]
export type Metadata = {
    --[=[
        The name of the language, in English.
    ]=]
    name: string,
    --[=[
        The name of the language, in the language itself.
    ]=]
    nativeName: string,
    --[=[
        The CLDR code for the language.
    ]=]
    cldrCode: string,
    --[=[
        The Roblox \`LocaleId\` for the language.
    ]=]
    robloxLocaleId: string,
}

--[=[
    A mapping of supported languages to their metadata.
]=]
module.LanguageMetadata = {
${languageMetadataEntries}
} :: { [LanguageCode]: Metadata }

--[=[
    Pluralization functions for a supported language.
]=]
export type PluralizationFunctions = {
    cardinal: (operands: Operands) -> PluralizationCount,
    cardinalCounts: { PluralizationCount },
    ordinal: (operands: Operands) -> PluralizationCount,
    ordinalCounts: { PluralizationCount },
}

--[=[
    Data on how numbers should be formatted.
]=]
export type NumberFormattingData = {
    symbols: {
        decimal: string,
        group: string,
        minusSign: string,
        plusSign: string,
        percentSign: string,
        infinity: string,
        nan: string,
    },
    grouping: {
        primary: number,
        secondary: number,
    },
    compact: {
        short: { [string]: { [string]: string } },
        long: { [string]: { [string]: string } },
    },
}

--[=[
    The pluralization rules and number formatting data for a supported language.
]=]
export type LanguageConfiguration = {
    pluralization: PluralizationFunctions,
    numberFormatting: NumberFormattingData,
}

--[=[
    Get the configuration for a supported language.

    @param languageCode The \`LanguageCode\` to get the configuration for.
    @return The configuration for the specified language.
]=]
function module.getLanguageConfiguration(
    languageCode: LanguageCode
): LanguageConfiguration
    local require = require
    return require("./data/" .. languageCode) :: LanguageConfiguration
end

return module
`;
};

/**
 * Generate the `src/data` init scripts (`init.luau` and `init.d.ts`).
 *
 * @param languages The supported languages.
 * @returns A success tuple, or a failure tuple describing what went wrong.
 */
export const generateInitScripts = (
    languages: Language[],
): [true] | [false, { code: "writeFail"; error: Error }] => {
    const outputDirectory = path.join(import.meta.dirname, "..", "src", "data");
    try {
        mkdirSync(outputDirectory, { recursive: true });
        writeFileSync(
            path.join(outputDirectory, "init.luau"),
            createInitLuau(languages),
        );
        writeFileSync(
            path.join(outputDirectory, "init.d.ts"),
            createInitTypescriptDefs(languages),
        );
    } catch (error) {
        return [
            false,
            {
                code: "writeFail",
                error:
                    error instanceof Error ? error : new Error(String(error)),
            },
        ];
    }

    return [true];
};
